"""
Semantic Task Correctness Evaluator
Project: mcp-inventory-bench
Author: Anand S. Suchak

Evaluates whether tool arguments generated by the LLM not only pass structural
JSON Schema validation, but also faithfully execute the user's domain instructions:
1. Destination Warehouse Routing (e.g. East depot -> WH-US-EAST)
2. Reorder Quantities (e.g. 50 units -> total line item quantity matches)
3. Priority Setting (e.g. urgent/emergency -> CRITICAL or EXPEDITED)
4. Specific SKU Matching (when explicitly mentioned in prompt)
"""

import re
from typing import Dict, Any, Tuple, List, Optional
from trace.paraphraser import BlindedTask

def extract_requested_quantity(intent_text: str) -> Optional[int]:
    """Extract primary numeric quantity from user intent text."""
    # Word numbers mapping
    word_to_num = {
        "ten": 10, "fifteen": 15, "twenty": 20, "twenty-five": 25, "twenty five": 25,
        "thirty": 30, "thirty-five": 35, "thirty five": 35, "forty": 40, "forty-five": 45,
        "forty five": 45, "fifty": 50, "fifty-five": 55, "fifty five": 55, "sixty": 60,
        "seventy": 70, "eighty": 80, "ninety": 90, "ninety-five": 95, "hundred": 100,
        "one hundred": 100
    }
    lower = intent_text.lower()
    for w, num in word_to_num.items():
        if re.search(r'\b' + re.escape(w) + r'\b', lower):
            return num

    m = re.search(r'\b(\d{2,4})\b', intent_text)
    if m:
        return int(m.group(1))
    return None

def extract_requested_destination(intent_text: str) -> Optional[str]:
    """Determine expected warehouse code from destination hints in intent."""
    lower = intent_text.lower()
    if any(k in lower for k in ["east", "atlantic"]):
        return "WH-US-EAST"
    elif any(k in lower for k in ["west", "pacific"]):
        return "WH-US-WEST"
    elif "eu" in lower or "europe" in lower:
        return "WH-EU-CENTRAL"
    elif "apac" in lower or "asia" in lower:
        return "WH-APAC-SOUTH"
    return None

def extract_expected_priority(intent_text: str) -> Optional[List[str]]:
    """Determine expected priority level if expedited or urgent."""
    lower = intent_text.lower()
    if any(k in lower for k in ["urgent", "rush", "emergency", "expedite", "critical", "highest priority", "line stoppage", "disruption", "severity"]):
        return ["CRITICAL", "EXPEDITED"]
    return ["STANDARD"]

def extract_mentioned_sku(intent_text: str) -> Optional[str]:
    """Extract explicit SKU identifier if present in user prompt."""
    m = re.search(r'\b(SKU-\d{5})\b', intent_text, re.IGNORECASE)
    if m:
        return m.group(1).upper()
    return None

def evaluate_task_correctness(task: BlindedTask, args: Dict[str, Any]) -> Tuple[bool, List[str]]:
    """
    Evaluate domain correctness of tool arguments against the user intent.
    Returns:
        (is_correct: bool, failure_reasons: List[str])
    """
    failures = []
    if not isinstance(args, dict):
        return False, ["Arguments is not a valid JSON dictionary."]

    intent = task.user_intent

    # 1. Warehouse Routing Verification
    expected_wh = extract_requested_destination(intent)
    if expected_wh:
        actual_wh = args.get("warehouse_code")
        if actual_wh != expected_wh:
            failures.append(f"Destination mismatch: user requested '{expected_wh}', but received '{actual_wh}'.")

    # 2. Quantity Verification
    expected_qty = extract_requested_quantity(intent)
    if expected_qty and "items" in args and isinstance(args["items"], list):
        total_actual_qty = sum(item.get("quantity", 0) for item in args["items"] if isinstance(item, dict))
        if total_actual_qty != expected_qty and total_actual_qty < expected_qty:
            failures.append(f"Quantity mismatch: expected at least {expected_qty} units, but tool call ordered {total_actual_qty}.")

    # 3. Priority Alignment
    expected_priorities = extract_expected_priority(intent)
    if expected_priorities and "order_priority" in args:
        actual_prio = args.get("order_priority")
        if actual_prio not in expected_priorities:
            failures.append(f"Priority mismatch: expected one of {expected_priorities}, but got '{actual_prio}'.")

    # 4. Specific SKU Alignment
    expected_sku = extract_mentioned_sku(intent)
    if expected_sku and "items" in args and isinstance(args["items"], list):
        actual_skus = [item.get("sku") for item in args["items"] if isinstance(item, dict)]
        if expected_sku not in actual_skus:
            failures.append(f"SKU mismatch: prompt specified '{expected_sku}', which was not found in items {actual_skus}.")

    is_correct = len(failures) == 0
    return is_correct, failures
